export const ALL_LESSONS: (Lesson & { levelId: string; levelTitle: string; levelNumber: number })[] = LEVELS.flatMap((l) =>
  l.lessons.map((x) => ({ ...x, levelId: l.id, levelTitle: l.title, levelNumber: l.number }))
);

export const TOTAL_LESSONS = ALL_LESSONS.length;

export function findLesson(id: string) {
  return ALL_LESSONS.find((l) => l.id === id);
}

export const RANKS = [
  { min: 0, title: "Kitchen Newcomer" },
  { min: 3, title: "Prep Cook" },
  { min: 8, title: "Line Cook" },
  { min: 15, title: "Sous Chef" },
  { min: 25, title: "Chef de Cuisine" },
  { min: 35, title: "Executive Chef" },
];

export function rankFor(completed: number) {
  let current = RANKS[0];
  let next: (typeof RANKS)[number] | null = null;
  for (let i = 0; i < RANKS.length; i++) {
    if (completed >= RANKS[i].min) {
      current = RANKS[i];
      next = RANKS[i + 1] || null;
    }
  }
  return { current, next };
}

/** The first lesson (in path order) not yet completed. */
export function nextLesson(done: Set<string>) {
  return ALL_LESSONS.find((l) => !done.has(l.id)) || null;
}
